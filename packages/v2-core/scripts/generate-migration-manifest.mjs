// Writes src/generated/migration-manifest.ts: the authoring migrations this build expects, with
// their SHA-256. Code bundled into Studio cannot read the migrations directory at runtime, so the
// health check compares the database with this list instead. A unit test keeps it current.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const directory = new URL('../migrations/', import.meta.url);
const entries = readdirSync(directory)
	.filter((name) => /^\d{3}_[a-z0-9_]+\.sql$/.test(name))
	.sort()
	.map((version) => ({
		version,
		sha256: createHash('sha256')
			.update(readFileSync(new URL(version, directory), 'utf8'))
			.digest('hex')
	}));
const objects = entries.map(
	(entry) => `\t{\n\t\tversion: '${entry.version}',\n\t\tsha256: '${entry.sha256}'\n\t}`
);
writeFileSync(
	new URL('../src/generated/migration-manifest.ts', import.meta.url),
	`// Generated by scripts/generate-migration-manifest.mjs from migrations/. Do not edit.\n` +
		`export const authoringMigrationManifest: readonly { version: string; sha256: string }[] = [\n` +
		`${objects.join(',\n')}\n];\n`
);
