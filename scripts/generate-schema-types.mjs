import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileFromFile } from 'json-schema-to-typescript';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMAS = join(ROOT, 'data', 'schemas');
const OUTPUT = join(ROOT, 'src', 'lib', 'types', 'generated', 'production.ts');
const checkOnly = process.argv.includes('--check');
const inputs = [
	['ProductionContextsFile', 'production-contexts.schema.json'],
	['ProviderCapabilitiesFile', 'provider-capabilities.schema.json'],
	['ContinuityLedgerFile', 'continuity-ledger.schema.json'],
	['GenerationPlanFile', 'generation-plan.schema.json']
];
const chunks = ['/* Generated by npm run schema:types. Do not edit directly. */\n'];
for (const [name, file] of inputs) {
	chunks.push(
		await compileFromFile(join(SCHEMAS, file), {
			bannerComment: '',
			cwd: SCHEMAS,
			style: { singleQuote: true, useTabs: true, trailingComma: 'none' },
			unreachableDefinitions: false,
			declareExternallyReferenced: true,
			customName: () => name
		})
	);
}
const output = `${chunks.join('\n')}\n`;
if (checkOnly) {
	if (!existsSync(OUTPUT) || readFileSync(OUTPUT, 'utf8') !== output) {
		throw new Error('Generated schema types are stale; run npm run schema:types');
	}
} else {
	mkdirSync(dirname(OUTPUT), { recursive: true });
	writeFileSync(OUTPUT, output, 'utf8');
}
console.log(`schema:types:${checkOnly ? 'check' : 'build'} OK`);
